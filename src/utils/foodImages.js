/**
 * Returns an appetizing commercial food image for any menu item
 * 1. Matches menuItemId or id against DISH_IMAGES_BY_ID (guarantees 100% 1-to-1 unique mapping for all 53 live items)
 * 2. Matches exact dish name against curated DISH_IMAGES
 * 3. Matches dish name stripped of parenthetical quantity
 * 4. Matches partial dish name against DISH_IMAGES
 * 5. Checks item.imageUrl / item.image_url if provided
 * 6. Falls back to category image
 */
export function getFoodImage(item) {
  const id = item?.menuItemId ?? item?.id
  if (id !== undefined && id !== null && DISH_IMAGES_BY_ID[id]) {
    return DISH_IMAGES_BY_ID[id]
  }

  const name = (item?.name || '').toLowerCase().trim()

  if (name && DISH_IMAGES[name]) {
    return DISH_IMAGES[name]
  }

  const cleanName = name.replace(/\s*\([^)]*\)/g, '').trim()
  if (cleanName && DISH_IMAGES[cleanName]) {
    return DISH_IMAGES[cleanName]
  }

  const sortedKeys = Object.keys(DISH_IMAGES).sort((a, b) => b.length - a.length)
  for (const key of sortedKeys) {
    if (key.length >= 5 && (name.includes(key) || key.includes(name))) {
      return DISH_IMAGES[key]
    }
  }

  if (item?.imageUrl && typeof item.imageUrl === 'string' && item.imageUrl.trim().length > 0) {
    return item.imageUrl.trim()
  }
  if (item?.image_url && typeof item.image_url === 'string' && item.image_url.trim().length > 0) {
    return item.image_url.trim()
  }

  const cat = (item?.category || '').toUpperCase()
  if (cat && CATEGORY_IMAGES[cat]) {
    return CATEGORY_IMAGES[cat]
  }

  return CATEGORY_IMAGES.DEFAULT
}
